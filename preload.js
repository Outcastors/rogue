const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('rogue', {
  // folders / settings
  pickFolder: () => ipcRenderer.invoke('dialog:pickFolder'),
  settingsGet: () => ipcRenderer.invoke('settings:get'),
  settingsSet: (patch) => ipcRenderer.invoke('settings:set', patch),
  // engine
  opencodeEnsure: (dir) => ipcRenderer.invoke('opencode:ensure', dir),
  opencodeStop: () => ipcRenderer.invoke('opencode:stop'),
  opencodeAlive: () => ipcRenderer.invoke('opencode:alive'),
  engineVersion: () => ipcRenderer.invoke('engine:version'),
  appVersion: () => ipcRenderer.invoke('app:version'),
  engineUpgrade: () => ipcRenderer.invoke('engine:upgrade'),
  engineStats: (days) => ipcRenderer.invoke('engine:stats', days),
  engineModels: (provider) => ipcRenderer.invoke('engine:models', provider),
  providerConfigured: () => ipcRenderer.invoke('provider:configured'),
  onEngineProgress: (cb) => ipcRenderer.on('engine:progress', (_e, d) => cb(d)),
  onUpgradeLog: (cb) => ipcRenderer.on('engine:upgrade-log', (_e, d) => cb(d)),
  // auth
  authList: () => ipcRenderer.invoke('auth:list'),
  authSave: (providerId, key) => ipcRenderer.invoke('auth:save', providerId, key),
  authRemove: (providerId) => ipcRenderer.invoke('auth:remove', providerId),
  // config: model / mcp / plugins / ollama
  configGet: () => ipcRenderer.invoke('config:get'),
  configSetModel: (model) => ipcRenderer.invoke('config:setModel', model),
  mcpAdd: (spec) => ipcRenderer.invoke('mcp:add', spec),
  mcpRemove: (name) => ipcRenderer.invoke('mcp:remove', name),
  mcpToggle: (name, enabled) => ipcRenderer.invoke('mcp:toggle', name, enabled),
  pluginInstall: (name) => ipcRenderer.invoke('plugin:install', name),
  onPluginLog: (cb) => ipcRenderer.on('plugin:log', (_e, d) => cb(d)),
  ollamaStatus: () => ipcRenderer.invoke('ollama:status'),
  ollamaConnect: () => ipcRenderer.invoke('ollama:connect'),
  // hunter / prompts / backup
  hunterStatus: () => ipcRenderer.invoke('hunter:status'),
  hunterInstall: () => ipcRenderer.invoke('hunter:install'),
  hunterRemove: () => ipcRenderer.invoke('hunter:remove'),
  promptSend: (text) => ipcRenderer.invoke('prompt:send', text),
  sessionsBackup: () => ipcRenderer.invoke('sessions:backup'),
  sessionsList: () => ipcRenderer.invoke('sessions:list'),
  sessionsDelete: (id) => ipcRenderer.invoke('sessions:delete', id),
  sessionsExport: (id) => ipcRenderer.invoke('sessions:export', id),
  sessionsBackup: () => ipcRenderer.invoke('sessions:backup'),
  backupPickDir: () => ipcRenderer.invoke('backup:pickdir'),
  backupAuto: () => ipcRenderer.invoke('backup:auto'),
  agentsList: () => ipcRenderer.invoke('agents:list'),
  agentsRead: (name) => ipcRenderer.invoke('agents:read', name),
  agentsSave: (name, content) => ipcRenderer.invoke('agents:save', name, content),
  agentsDelete: (name) => ipcRenderer.invoke('agents:delete', name),
  desktopInstall: () => ipcRenderer.invoke('desktop:install'),
  // terminal
  termAvailable: () => ipcRenderer.invoke('term:available'),
  termSpawn: (cwd) => ipcRenderer.invoke('term:spawn', cwd),
  termWrite: (id, data) => ipcRenderer.invoke('term:write', id, data),
  termResize: (id, cols, rows) => ipcRenderer.invoke('term:resize', id, cols, rows),
  termKill: (id) => ipcRenderer.invoke('term:kill', id),
  onTermData: (cb) => ipcRenderer.on('term:data', (_e, d) => cb(d)),
  onTermExit: (cb) => ipcRenderer.on('term:exit', (_e, d) => cb(d)),
  // misc
  windowClose: () => ipcRenderer.invoke('window:close'),
  folderCreate: (name, dir) => ipcRenderer.invoke('folder:create', name, dir),
  openExternal: (url) => ipcRenderer.invoke('shell:open', url),
  onTrayOpenOpencode: (cb) => ipcRenderer.on('tray:open-opencode', () => cb()),
});
